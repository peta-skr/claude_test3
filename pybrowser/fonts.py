# The glyph used for any character we don't have: a hollow box.
_MISSING = ["#####", "#   #", "#   #", "#   #", "#   #", "#   #", "#####"]


def _art_to_bits(art: List[str]) -> Tuple[int, ...]:
    """Convert 7 rows of art into 7 integers, one bitmask per row."""
    rows = []
    for line in art:
        bits = 0
        for x in range(GLYPH_W):
            if x < len(line) and line[x] == "#":
                bits |= 1 << (GLYPH_W - 1 - x)
        rows.append(bits)
    return tuple(rows)


# Pre-compute the bitmask form once at import time.
GLYPHS: Dict[str, Tuple[int, ...]] = {
    ch: _art_to_bits(art) for ch, art in _GLYPHS_ART.items()
}
MISSING_GLYPH = _art_to_bits(_MISSING)


def glyph_rows(ch: str) -> Tuple[int, ...]:
    """Return the 7 row-bitmasks for ``ch`` (a box for unknown characters)."""
    if ch in GLYPHS:
        return GLYPHS[ch]
    if ch == "\t":
        return GLYPHS[" "]
    return MISSING_GLYPH


class Font:
    """Font metrics for a given pixel size / weight / style.

    A CSS ``font-size`` in pixels is mapped to an integer ``scale`` used to
    blow up the 5x7 glyph.  All metrics are reported in device pixels so the
    layout engine can position text precisely.
    """

    __slots__ = ("size", "weight", "style", "scale", "char_width", "char_height",
                 "line_height", "ascent", "descent")

    def __init__(self, size: float = 16.0, weight: str = "normal",
                 style: str = "normal") -> None:
        self.size = size
        self.weight = weight
        self.style = style
        self.scale = max(1, round(size / 8.0))
        embolden = 1 if weight in ("bold", "bolder") else 0
        self.char_width = GLYPH_W * self.scale + self.scale + embolden
        self.char_height = GLYPH_H * self.scale
        # Comfortable line spacing above/below the glyph box.
        self.line_height = self.char_height + 2 * self.scale
        self.ascent = self.char_height
        self.descent = 2 * self.scale

    def measure(self, text: str) -> int:
        return len(text) * self.char_width

    def __repr__(self) -> str:
        return f"Font(size={self.size}, {self.weight}, {self.style})"
